juce::String num (float v)
{
    auto s = juce::String (v, 4);
    while (s.contains (".") && s.endsWithChar ('0') && ! s.endsWith (".0"))
        s = s.dropLastCharacters (1);
    return s;
}

// Flattens nested arrays (rows of weights) into `out`.
bool flatten (const juce::var& v, juce::Array<float>& out)
{
    if (auto* a = v.getArray())
    {
        for (const auto& x : *a)
            if (! flatten (x, out)) return false;
        return true;
    }
    if (v.isDouble() || v.isInt() || v.isInt64())
    {
        out.add ((float) (double) v);
        return std::isfinite (out.getLast());
    }
    return false;
}
