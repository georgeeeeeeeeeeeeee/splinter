bool tablesFromJson (const juce::String& text, dsp::MacroTables& into, juce::String& error)
{
    juce::var json;
    if (const auto r = juce::JSON::parse (text, json); r.failed())
    {
        error = "JSON: " + r.getErrorMessage();
        return false;
    }
    auto* obj = json.getDynamicObject();
    if (obj == nullptr)
    {
        error = "not a JSON object";
        return false;
    }
    auto t = into;
    int count = 0;
    const auto* fields = dsp::MacroTables::fields (count);
    for (const auto& prop : obj->getProperties())
    {
        const auto key = prop.name.toString();
        if (key.startsWithChar ('_'))
            continue;
        const dsp::MacroTables::Field* f = nullptr;
        for (int i = 0; i < count; ++i)
            if (key == fields[i].name) f = &fields[i];
        if (f == nullptr)
        {
            error = "unknown key '" + key + "'";
            return false;
        }
        juce::Array<float> values;
        if (! flatten (prop.value, values) || values.size() != f->count)
        {
            error = "'" + key + "' needs " + juce::String (f->count) + " number" + (f->count > 1 ? "s" : "");
            return false;
        }
        std::copy (values.begin(), values.end(), t.at (*f));
    }
    into = t;
    return true;
}

juce::String tablesToJson (const dsp::MacroTables& t)
{
    int count = 0;
    const auto* fields = dsp::MacroTables::fields (count);
    juce::String s ("{\n  \"_about\": \"Splinter Macro mode tuning. Dev builds of the plug-in reload this file when it's saved; "
                    "fault-render reads it too. Each key's meaning is in _notes.\",\n");
    s << "  \"_notes\": {\n";
    for (int i = 0; i < count; ++i)
        s << "    \"" << fields[i].name << "\": " << juce::JSON::toString (juce::String (fields[i].about)) << (i + 1 < count ? ",\n" : "\n");
    s << "  },\n";
    for (int i = 0; i < count; ++i)
    {
        const auto& f = fields[i];
        const float* v = t.at (f);
        s << "  \"" << f.name << "\": ";
        if (f.count == 1)
            s << num (v[0]);
        else if (f.columns > 1)
        {
            s << "[\n";
            for (int r = 0; r < f.count / f.columns; ++r)
            {
                s << "    [";
                for (int c = 0; c < f.columns; ++c) s << num (v[r * f.columns + c]) << (c + 1 < f.columns ? ", " : "");
                s << "]" << (r + 1 < f.count / f.columns ? ",\n" : "\n");
            }
            s << "  ]";
        }
        else
        {
            s << "[";
            for (int k = 0; k < f.count; ++k) s << num (v[k]) << (k + 1 < f.count ? ", " : "");
            s << "]";
        }
        s << (i + 1 < count ? ",\n" : "\n");
    }
    return s + "}\n";
}

juce::String tablesToCpp (const dsp::MacroTables& t)
{
    int count = 0;
    const auto* fields = dsp::MacroTables::fields (count);
    juce::String s ("// Generated by: fault-render --bake-tables tuning/macro_tables.json\n"
                    "// Do not edit by hand: tune tuning/macro_tables.json, then bake.\n");
    const auto f32 = [] (float v) { auto x = num (v); if (! x.contains (".")) x << ".0"; return x + "f"; };
    for (int i = 0; i < count; ++i)
    {
        const auto& f = fields[i];
        const float* v = t.at (f);
        s << "t." << f.name << " = ";
        if (f.count == 1)
            s << f32 (v[0]);
        else if (f.columns > 1)
        {
            s << "{\n";
            for (int r = 0; r < f.count / f.columns; ++r)
            {
                s << "    ";
                for (int c = 0; c < f.columns; ++c)
                {
                    const int k = r * f.columns + c;
                    s << f32 (v[k]) << (k + 1 < f.count ? (c + 1 < f.columns ? ", " : ",") : "");
                }
                s << (r + 1 < f.count / f.columns ? "\n" : " }");
            }
        }
        else
        {
            s << "{ ";
            for (int k = 0; k < f.count; ++k) s << f32 (v[k]) << (k + 1 < f.count ? ", " : " }");
        }
        s << ";\n";
    }
    return s;
}
